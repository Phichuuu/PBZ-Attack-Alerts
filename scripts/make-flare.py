"""Build original, antialiased flare masks. No game or third-party art is used."""
from pathlib import Path
from io import BytesIO
from PIL import Image, ImageDraw, ImageFilter, ImageChops

ROOT = Path(__file__).resolve().parents[1]
N, SS = 256, 3

def star(horizontal, vertical, waist):
    im = Image.new('L', (N*SS, N*SS))
    points = [(0,-vertical),(waist,-waist),(horizontal,0),(waist,waist),
              (0,vertical),(-waist,waist),(-horizontal,0),(-waist,-waist)]
    ImageDraw.Draw(im).polygon([((128+x)*SS,(128+y)*SS) for x,y in points], fill=255)
    return im.resize((N,N), Image.Resampling.LANCZOS)

flare = star(118, 100, 9)
core = star(98, 80, 3.5)
# Keep the tip-to-tip size identical. Fill more of the narrow yellow rays and
# add a small dark silhouette for contrast against bright armour/backgrounds.
gold_flare = star(118, 100, 14)
gold_core = star(98, 80, 4.7)
gold_edge = gold_flare.filter(ImageFilter.MaxFilter(5)).filter(ImageFilter.GaussianBlur(0.85))
halo = ImageChops.lighter(flare.filter(ImageFilter.GaussianBlur(7)),
                          flare.filter(ImageFilter.GaussianBlur(19)))
# Boost bloom without changing the razor-thin luminous centre.
halo = halo.point(lambda x: min(255, int(x*2.5)))
ring = Image.new('L', (N*SS,N*SS))
draw = ImageDraw.Draw(ring)
for a in (8,98,188,278):
    draw.arc((39*SS,39*SS,217*SS,217*SS),a,a+60,fill=235,width=2*SS)
ring = ring.resize((N,N), Image.Resampling.LANCZOS)

assets = {}
for name, mask in [('halo',halo),('flare',flare),('core',core),('ring',ring),
                   ('goldFlare',gold_flare),('goldCore',gold_core),('goldEdge',gold_edge)]:
    rgba = Image.new('RGBA',(N,N),(255,255,255,0)); rgba.putalpha(mask)
    buf=BytesIO(); rgba.save(buf,format='PNG',optimize=True)
    assets[name]=buf.getvalue().hex()
(ROOT/'src'/'flare-assets.ts').write_text(
    '// Original masks generated by scripts/make-flare.py; PNG data in hexadecimal.\n'+
    'export const flarePng = {\n'+''.join(f"    {k}: '{v}',\n" for k,v in assets.items())+'};\n',encoding='utf-8')

# A standalone still for art review, independent of the game overlay.
preview=Image.new('RGBA',(768,320),(18,22,25,255))
for cx,col,angle in [(210,(255,188,26),-10),(558,(255,38,48),-45)]:
    layers = [(halo,col,1 if cx==210 else .85),(ring,col,.35)]
    if cx==210: layers += [(gold_edge,(29,16,3),.55),(gold_flare,col,1),(gold_core,(255,255,235),1)]
    else: layers += [(flare,col,1),(core,(255,255,235),1)]
    for mask,color,opacity in layers:
        layer=Image.new('RGBA',(N,N),(*color,0)); layer.putalpha(mask.point(lambda a:int(a*opacity)))
        layer=layer.rotate(angle,resample=Image.Resampling.BICUBIC)
        preview.alpha_composite(layer,(cx-128,32))
(ROOT/'art').mkdir(exist_ok=True)
preview.convert('RGB').save(ROOT/'art'/'flare-preview.png')
# Same-size comparison on dark and bright synthetic backgrounds. No screenshot
# processing: these are newly drawn geometry masks from the same source above.
compare=Image.new('RGBA',(640,360))
for row,background in enumerate([(27,31,27,255),(173,163,127,255)]):
    compare.paste(background,(0,row*180,640,(row+1)*180))
    for column,enhanced in enumerate([False,True]):
        layers=[(halo,(255,188,26),1 if enhanced else .8)]
        if enhanced: layers += [(gold_edge,(29,16,3),.55)]
        layers += [(gold_flare if enhanced else flare,(255,188,26),1),
                   (gold_core if enhanced else core,(255,255,235),1)]
        for mask,color,opacity in layers:
            layer=Image.new('RGBA',(N,N),(*color,0)); layer.putalpha(mask.point(lambda a:int(a*opacity)))
            layer=layer.rotate(-10,resample=Image.Resampling.BICUBIC).resize((154,154),Image.Resampling.LANCZOS)
            compare.alpha_composite(layer,(column*320+83,row*180+13))
compare.convert('RGB').save(ROOT/'art'/'yellow-contrast-comparison.png')
print('Generated original flare masks and preview')
